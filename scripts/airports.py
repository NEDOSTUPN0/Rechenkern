#!/usr/bin/env python3
"""Builds crates/rechenkern/src/zones/airports.txt: IATA code, time zone, latitude, longitude.

Usage: scripts/airports.py airports.csv wordlist.txt > crates/rechenkern/src/zones/airports.txt

- airports.csv: https://davidmegginson.github.io/ourairports-data/airports.csv
  (OurAirports, public domain)
- wordlist.txt: English words, e.g. share/dict/wamerican.35 from nixpkgs#scowl

Large airports, and medium ones of capitals and places people fly to (MEDIUM below).
OurAirports has no time zones: an airport takes the zone of its country when the
country has only one (tzdb's zone.tab), else of the city it serves (OurAirports'
municipality) in crates/rechenkern/src/zones/cities.txt, else of the nearest city of its
country or zone_coordinates.txt's principal place of one of its zones, so a city across
a border never decides (Malé, Gold Coast, Easter Island). Codes that are English words ("MAN", "SEA") or
words the engine knows (any three-letter word quoted in its parser, units and currencies:
"JAN", "NUM", "MIN") count only in capitals, so they are written in capitals; so are codes
of currencies ("MAD") and codes that name a city of their own ("WAW", "SAN"): in capitals
they are the airport, otherwise the currency or the city. Older codes people still use
come from the airport's keywords ("TSE" for Astana) or, for closed airports, LEGACY;
they count only in capitals too.
"""

import csv
import math
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent / "crates/rechenkern/src"

# Medium airports worth knowing: capitals and places people fly to.
MEDIUM = {
    "AGR", "ARK", "ASP", "BHD", "BNK", "BOH", "CBR", "EAS", "FAI", "GRB", "GRX", "HLZ", "HRI", "HRK", "ICT", "INV",
    "JAN", "JMK", "JOG", "LTK", "LTX", "PKR", "RFD", "ROT", "SGF", "SOU", "SPI", "TGU", "TLH", "TSV", "UDR",
    "AFW", "MCM",
}

# Codes of closed airports and the airport that took their place.
LEGACY = {"REP": "SAI", "TIP": "MJI", "SXF": "BER", "TXL": "BER"}
ZONE_TAB = Path("/usr/share/zoneinfo/zone.tab")


def cities():
    rows = []
    for line in (ROOT / "zones/cities.txt").read_text().splitlines():
        if line.startswith("#"):
            continue
        name, zone, latitude, longitude = line.split("\t")
        rows.append((name, zone, float(latitude), float(longitude)))
    return rows


def distance(a, b):
    """Great-circle distance in radians."""
    (lat1, lon1), (lat2, lon2) = (map(math.radians, p) for p in (a, b))
    h = math.sin((lat2 - lat1) / 2) ** 2 + math.cos(lat1) * math.cos(lat2) * math.sin((lon2 - lon1) / 2) ** 2
    return 2 * math.asin(math.sqrt(h))


def country_zones():
    """Country code -> its zones, from tzdb's zone.tab."""
    zones = {}
    for line in ZONE_TAB.read_text().splitlines():
        if not line.startswith("#"):
            country, _, zone, *_ = line.split("\t")
            zones.setdefault(country, set()).add(zone)
    return zones


def zone_of(row, places, zones):
    """The airport's zone: its country's only one, the city it serves, or the nearest city of its country."""
    here = (float(row["latitude_deg"]), float(row["longitude_deg"]))
    own = zones.get(row["iso_country"], set())
    if len(own) == 1:
        return next(iter(own))
    near = lambda c: distance(here, (c[2], c[3]))
    served = [c for c in places if c[0] == row["municipality"].lower() and near(c) < 150 / 6371]
    if served:
        return min(served, key=near)[1]
    inside = [c for c in places + principal_places() if c[1] in own] or places
    return min(inside, key=near)[1]


def principal_places():
    """Each zone's principal place (zone_coordinates.txt), for islands without a big city: Easter Island."""
    rows = []
    for line in (ROOT / "zones/zone_coordinates.txt").read_text().splitlines():
        if not line.startswith("#"):
            zone, latitude, longitude = line.split("\t")
            rows.append((zone, zone, float(latitude), float(longitude)))
    return rows


def main(airports_path, words_path):
    words = {w.strip().lower() for w in open(words_path, encoding="latin-1") if w.strip().isalpha()}
    currencies = set(re.findall(r'(?:fiat|crypto)\("([A-Z]{3})"', (ROOT / "currency.rs").read_text()))
    sources = [*(ROOT / "parser").glob("*.rs"), ROOT / "units/table.rs", ROOT / "currency.rs"]
    for source in sources:
        words |= {w.lower() for w in re.findall(r'"([A-Za-z]{3})"', source.read_text())}
    places = cities()
    zones = country_zones()
    names = {name for name, *_ in places}
    print("# IATA airport code -> IANA time zone, latitude and longitude. Codes in capitals")
    print("# count only in capitals. Generated by scripts/airports.py from OurAirports (public")
    print("# domain), zones by country, served city or nearest city. Do not edit by hand.")
    rows = [r for r in csv.DictReader(open(airports_path, encoding="utf-8")) if re.fullmatch(r"[A-Z]{3}", r["iata_code"])]
    taken = {r["iata_code"] for r in rows}
    chosen = {r["iata_code"]: r for r in rows if r["type"] == "large_airport" or r["iata_code"] in MEDIUM}
    codes = dict(chosen)
    for row in chosen.values():
        for old in re.findall(r"\b[A-Z]{3}\b", row["keywords"]):
            if old not in taken:
                codes.setdefault(old, row)
    for old, new in LEGACY.items():
        codes.setdefault(old, chosen[new])
    for code, row in sorted(codes.items()):
        here = (float(row["latitude_deg"]), float(row["longitude_deg"]))
        zone = zone_of(row, places, zones)
        word = code.lower() in words or code in currencies or code.lower() in names or code not in chosen
        written = code if word else code.lower()
        print(f"{written} = {zone} {here[0]:.2f} {here[1]:.2f}")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
