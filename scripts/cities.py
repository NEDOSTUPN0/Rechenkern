#!/usr/bin/env python3
"""Builds crates/rechenkern/src/zones/cities.txt from GeoNames: name, zone, latitude, longitude.

Usage: scripts/cities.py cities15000.txt wordlist.txt > crates/rechenkern/src/zones/cities.txt

- cities15000.txt: https://download.geonames.org/export/dump/cities15000.zip
- wordlist.txt: English words, e.g. share/dict/wamerican.35 from nixpkgs#scowl
"""

import re
import sys
import unicodedata

# Alternate names are added only for big cities, to keep the file small.
ALTERNATES_FROM = 500_000
# Cities named like an English word must be this big to count ("Reading" yes, "Time" no).
WORD_NAMES_FROM = 200_000
# An alternate name stands for a city as if it had this much of its population: a
# smaller city of that name wins ("Parma" is Italy's, not an old name of Perm).
ALTERNATE_WEIGHT = 0.15
# Words too common in calculations to ever mean a city.
STOPWORDS = {"sale", "man", "gold", "hub", "bush", "delta", "mango", "lion", "shaping", "lander", "terminus"}

ASCII = re.compile(r"^[A-Za-z' .-]+$")


def key(name):
    return " ".join(name.lower().replace("-", " ").split())


def typed(name):
    """The name as the parser reads it: words of letters, which apostrophes may join
    ("n'djamena"); dots and other marks between them split words ("Fort St. John")."""
    words, word = [], ""
    for i, c in enumerate(name):
        after = name[i + 1] if i + 1 < len(name) else " "
        # Combining marks stay in the word: nobody types them apart.
        mark = word and unicodedata.category(c).startswith("M")
        if c.isalpha() or c == "_" or mark or (word and (c.isdigit() or (c in "'’" and after.isalpha()))):
            word += "'" if c == "’" else c
        else:
            words.append(word)
            word = ""
    return " ".join(w for w in words + [word] if w)


def degrees(text):
    # Two decimals are about a kilometer, a few seconds of sunrise; "+ 0" turns -0.0 into 0.0.
    return f"{round(float(text), 2) + 0:.2f}"


def main(cities_path, words_path):
    words = {w.strip().lower() for w in open(words_path, encoding="latin-1") if w.strip().isalpha()}
    best = {}  # key -> (weighed population, zone, latitude, longitude)
    for line in open(cities_path, encoding="utf-8"):
        fields = line.rstrip("\n").split("\t")
        name, ascii_name, alternates, zone = fields[1], fields[2], fields[3], fields[17]
        latitude, longitude = degrees(fields[4]), degrees(fields[5])
        population = int(fields[14] or 0)
        if not zone:
            continue
        country = fields[8]
        names = {key(name), key(ascii_name)}
        # "Donostia / San Sebastián" goes by either name.
        names |= {key(part) for n in (name, ascii_name) if " / " in n for part in n.split(" / ")}
        # "Nara-shi" is the city of Nara.
        if country == "JP":
            names |= {n.removesuffix(" shi") for n in names if n.endswith(" shi")}
        if population < WORD_NAMES_FROM:
            names -= words
        alternate_names = set()
        if population >= ALTERNATES_FROM:
            for alt in alternates.split(","):
                # Skip airport codes like "OZH" and alternates that are words ("Deli" for Delhi).
                if ASCII.match(alt) and not (alt.isupper() and len(alt) <= 4) and key(alt) not in words:
                    alternate_names.add(key(alt))
        for n in names | alternate_names:
            if len(n) < 3 or n in STOPWORDS:
                continue
            # The most populous place wins a shared name; an alternate name counts for less.
            weight = population * (ALTERNATE_WEIGHT if n not in names else 1)
            if n not in best or best[n][0] < weight:
                best[n] = (weight, zone, latitude, longitude)

    # Names as typed: "Fort St. John" is "fort st john", "'Afak" is "afak", "Banī Na‘īm" is "banī na īm".
    extra = {}
    for n in sorted(best, key=lambda s: s.encode("utf-8")):
        t = typed(n)
        if t != n and len(t) >= 3 and t not in words and t not in STOPWORDS and t not in best and t not in extra:
            extra[t] = best[n]
    best.update(extra)

    print("# City name -> IANA time zone, latitude and longitude, sorted by name for binary search.")
    print("# Generated by scripts/cities.py from GeoNames cities15000 (https://www.geonames.org),")
    print("# licensed under CC BY 4.0. Do not edit by hand.")
    for n in sorted(best, key=lambda s: s.encode("utf-8")):
        _, zone, latitude, longitude = best[n]
        print(f"{n}\t{zone}\t{latitude}\t{longitude}")


if __name__ == "__main__":
    main(*sys.argv[1:3])
