#!/usr/bin/env python3
"""Writes crates/rechenkern/src/zones/countries.txt: ISO 3166 code, name, currency and zones.

Names and zones come from the tz database (iso3166.tab and zone.tab, public domain), currencies
from glibc's locale data (the int_curr_symbol of each territory's locales) and the table below. Run on a system with
both installed: python3 scripts/countries.py > crates/rechenkern/src/zones/countries.txt
"""
import re
from collections import Counter, defaultdict
from pathlib import Path

TZ = Path("/usr/share/zoneinfo")
LOCALES = Path("/usr/share/i18n/locales")

names = {}
for line in (TZ / "iso3166.tab").read_text().splitlines():
    if line and not line.startswith("#"):
        code, name = line.split("\t")
        names[code] = name

zones = defaultdict(list)
for line in (TZ / "zone.tab").read_text().splitlines():
    if line and not line.startswith("#"):
        code, _, zone = line.split("\t")[:3]
        zones[code].append(zone)

# Each territory's locales name a currency; the most common one wins.
currencies = defaultdict(Counter)
for path in LOCALES.iterdir():
    text = path.read_text(errors="ignore")
    territory = re.search(r'^territory\s+"([^"]+)"', text, re.M)
    currency = re.search(r'^int_curr_symbol\s+"([A-Z]{3})', text, re.M)
    code = re.match(r"^[a-z]+_([A-Z]{2})", path.name)
    if currency and code:
        currencies[code.group(1)][currency.group(1)] += 1

# Territories glibc has no locale for, and currencies it still names after they were replaced.
CURRENCIES = {
    "AD": "EUR", "AI": "XCD", "AO": "AOA", "AS": "USD", "AX": "EUR", "BB": "BBD", "BF": "XOF",
    "BG": "EUR", "BI": "BIF", "BJ": "XOF", "BL": "EUR", "BM": "BMD", "BN": "BND", "BQ": "USD",
    "BS": "BSD", "BV": "NOK", "BY": "BYN", "BZ": "BZD", "CC": "AUD", "CF": "XAF", "CG": "XAF",
    "CI": "XOF", "CK": "NZD", "CM": "XAF", "CV": "CVE", "CX": "AUD", "CY": "EUR", "DM": "XCD",
    "EH": "MAD", "FK": "FKP", "FM": "USD", "FO": "DKK", "GA": "XAF", "GD": "XCD", "GF": "EUR",
    "GG": "GBP", "GI": "GIP", "GL": "DKK", "GM": "GMD", "GN": "GNF", "GP": "EUR", "GQ": "XAF",
    "GS": "GBP", "GU": "USD", "GW": "XOF", "GY": "GYD", "HM": "AUD", "HR": "EUR", "IM": "GBP",
    "IO": "USD", "JE": "GBP", "JM": "JMD", "KI": "AUD", "KM": "KMF", "KN": "XCD", "KP": "KPW",
    "KY": "KYD", "LC": "XCD", "LI": "CHF", "LR": "LRD", "LS": "LSL", "MC": "EUR", "MD": "MDL",
    "MF": "EUR", "MH": "USD", "ML": "XOF", "MO": "MOP", "MP": "USD", "MQ": "EUR", "MR": "MRU",
    "MS": "XCD", "MW": "MWK", "MZ": "MZN", "NA": "NAD", "NC": "XPF", "NE": "XOF", "NF": "AUD",
    "NR": "AUD", "NU": "NZD", "PF": "XPF", "PM": "EUR", "PN": "NZD", "PS": "ILS", "PW": "USD",
    "RE": "EUR", "SB": "SBD", "SH": "SHP", "SJ": "NOK", "SL": "SLE", "SM": "EUR", "SR": "SRD",
    "ST": "STN", "SX": "ANG", "SZ": "SZL", "TC": "USD", "TD": "XAF", "TF": "EUR", "TG": "XOF",
    "TK": "NZD", "TL": "USD", "TM": "TMT", "TT": "TTD", "TV": "AUD", "UM": "USD", "VA": "EUR",
    "VC": "XCD", "VE": "VES", "VG": "USD", "VI": "USD", "WF": "XPF", "YT": "EUR",
}

print("# ISO 3166 code, country, currency, time zones (the first is its principal one).")
print("# Generated by scripts/countries.py from the tz database (public domain) and glibc's")
print("# locales. Do not edit by hand.")
for code in sorted(names):
    currency = CURRENCIES.get(code) or (currencies[code].most_common(1)[0][0] if currencies[code] else "")
    print(f"{code}\t{names[code]}\t{currency}\t{','.join(zones[code])}")
