#!/usr/bin/env python3
"""Builds crates/rechenkern/src/zones/zone_coordinates.txt from the tz database.

Usage: scripts/zone_coordinates.py /usr/share/zoneinfo/zone.tab > crates/rechenkern/src/zones/zone_coordinates.txt

zone.tab gives each zone's principal place in ISO 6709 form: +DDMM+DDDMM or +DDMMSS+DDDMMSS.
"""

import re
import sys

ISO_6709 = re.compile(r"([+-])(\d\d)(\d\d)(\d\d)?([+-])(\d\d\d)(\d\d)(\d\d)?")


def degrees(sign, d, m, s):
    value = int(d) + int(m) / 60 + int(s or 0) / 3600
    # Two decimals are about a kilometer; "+ 0" turns -0.0 into 0.0.
    return f"{round(-value if sign == '-' else value, 2) + 0:.2f}"


def main(path):
    rows = []
    for line in open(path, encoding="ascii"):
        if line.startswith("#"):
            continue
        _, coordinates, zone = line.rstrip("\n").split("\t")[:3]
        parts = ISO_6709.fullmatch(coordinates).groups()
        rows.append((zone, degrees(*parts[:4]), degrees(*parts[4:])))
    print("# Zone -> latitude and longitude of its principal place, sorted by zone.")
    print("# Generated by scripts/zone_coordinates.py from the tz database's zone.tab (public domain).")
    for zone, latitude, longitude in sorted(rows):
        print(f"{zone}\t{latitude}\t{longitude}")


if __name__ == "__main__":
    main(sys.argv[1])
