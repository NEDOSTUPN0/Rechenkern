//! Currency table: ISO 4217 fiat currencies, precious metals and popular crypto.

/// A currency known to the engine. Exchange rates come from a [`crate::RateProvider`].
#[derive(Debug)]
pub struct Currency {
    /// ISO code, e.g. "USD".
    pub code: &'static str,
    /// English name: "US dollar".
    pub name: &'static str,
    pub plural: &'static str,
    /// Symbol printed before amounts ("$5.00"); codes are printed after otherwise.
    pub symbol: Option<&'static str>,
    /// Digits after the decimal point in formatted amounts.
    pub decimals: u8,
    /// Extra spellings: lowercase names match case-insensitively and get a plural
    /// with "-s", others match exactly.
    pub aliases: &'static [&'static str],
    pub crypto: bool,
}

const fn fiat(
    code: &'static str,
    name: &'static str,
    plural: &'static str,
    symbol: &'static str,
    decimals: u8,
    aliases: &'static [&'static str],
) -> Currency {
    let symbol = if symbol.is_empty() { None } else { Some(symbol) };
    Currency { code, name, plural, symbol, decimals, aliases, crypto: false }
}

const fn crypto(
    code: &'static str,
    name: &'static str,
    plural: &'static str,
    aliases: &'static [&'static str],
) -> Currency {
    Currency { code, name, plural, symbol: None, decimals: 8, aliases, crypto: true }
}

